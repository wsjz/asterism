    "#\n"
    "# The filter matches the project cards by name rather than by folder,\n"
    "# because where your Obsidian vault root sits is your choice. Narrow it\n"
    "# yourself if other notes are named like a card, for example:\n"
    '#     - file.folder.startsWith("projects")\n'
    "filters:\n"
    "  and:\n"
    '    - file.basename.endsWith("project")\n'
    "views:\n"
    "  - type: table\n"
    "    name: All projects\n"
    "    order:\n"
    "      - note.created\n"
    "      - note.title\n"
    "      - note.status\n"
    "      - note.pillar\n"
    "      - note.type\n"
    "      - note.platforms\n"
    "  - type: table\n"
    "    name: Waiting on me\n"
    "    filters:\n"
    "      and:\n"
    '        - note.status != "published"\n'
    '        - note.status != "retrospected"\n'
    '        - note.status != "dropped"\n'
    "    order:\n"
    "      - note.status\n"
    "      - note.created\n"
    "      - note.title\n"
    "      - note.promise\n"
    "  - type: table\n"
    "    name: Published\n"
